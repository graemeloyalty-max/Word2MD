"""Report builder: save research notes and export them to Markdown, Word (.docx) or PDF.

Every export ends with a Sources appendix listing each tool call behind the note, with its data
source and retrieval time, so a figure in the report can be traced back.
Reports are saved in data/reports/ as JSON (note + metadata + tool trail).
"""
from __future__ import annotations

import io
import json
import re
from dataclasses import asdict
from datetime import datetime, timezone
from pathlib import Path

from .core import config

DISCLAIMER = "Generated by the Global Equity Terminal with AI assistance. Research, not investment advice."
FONT_DIRS = [Path("/usr/share/fonts/truetype/dejavu"), Path("/usr/share/fonts/dejavu"), Path("/Library/Fonts"),
             Path.home() / ".fonts", Path("C:/Windows/Fonts")]


def _dir() -> Path:
    d = config.DATA_DIR / "reports"
    d.mkdir(parents=True, exist_ok=True)
    return d


def slug(text: str, n: int = 50) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:n] or "report"


def save(result, title: str | None = None) -> Path:
    data = asdict(result) if hasattr(result, "__dataclass_fields__") else dict(result)
    q = data["question"]
    data["title"] = title or data.get("title") or (q if len(q) <= 90 else q[:87].rsplit(" ", 1)[0] + "…")
    stamp = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S")
    path = _dir() / f"{stamp}_{slug(data['title'])}.json"
    path.write_text(json.dumps(data, indent=1, default=str))
    return path


def list_reports() -> list[dict]:
    out = []
    for p in sorted(_dir().glob("*.json"), reverse=True):
        try:
            d = json.loads(p.read_text())
            out.append({"path": p, "title": d.get("title", p.stem), "created": d.get("created", "")})
        except json.JSONDecodeError:
            continue
    return out


def load(path: Path) -> dict:
    return json.loads(Path(path).read_text())


def delete(path: Path) -> None:
    Path(path).unlink(missing_ok=True)


def sources_table(steps: list) -> list[list[str]]:
    rows = [["#", "Agent", "Tool", "Arguments", "Data source", "Retrieved"]]
    for i, s in enumerate(steps, 1):
        r = s.get("result", {}) if isinstance(s.get("result"), dict) else {}
        args = ", ".join(f"{k}={v}" for k, v in (s.get("args") or {}).items())
        src = r.get("source", "error: " + str(r.get("error", ""))[:60] if "error" in r else "")
        rows.append([str(i), s.get("agent", ""), s.get("tool", ""), args, str(src), str(r.get("as_of", ""))])
    return rows


def to_markdown(report: dict) -> str:
    parts = [f"# {report['title']}", f"_{report.get('created', '')} · question: {report['question']}_", "", report["note"].strip(), "",
             "## Sources", ""]
    rows = sources_table(report.get("steps", []))
    parts.append("| " + " | ".join(rows[0]) + " |")
    parts.append("|" + "---|" * len(rows[0]))
    parts += ["| " + " | ".join(c.replace("|", "/") for c in r) + " |" for r in rows[1:]]
    usage = report.get("usage") or {}
    if usage:
        parts += ["", "Models used: " + "; ".join(f"{a}: {u[3]} ({u[0]:,} in / {u[1]:,} out tokens)" for a, u in usage.items())]
    parts += ["", f"_{DISCLAIMER}_"]
    return "\n".join(parts)


# ---------------------------------------------------------------- tiny Markdown reader shared by Word and PDF

def blocks(md: str):
    """Yield (kind, payload): ('h', (level, text)), ('li', text), ('ol', text), ('table', rows), ('p', text)."""
    lines = md.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i].rstrip()
        if not line.strip():
            i += 1
            continue
        if line.lstrip().startswith("|"):
            rows = []
            while i < len(lines) and lines[i].lstrip().startswith("|"):
                cells = [c.strip() for c in lines[i].strip().strip("|").split("|")]
                if not all(re.fullmatch(r":?-{2,}:?", c) for c in cells if c):
                    rows.append(cells)
                i += 1
            yield "table", rows
            continue
        m = re.match(r"^(#{1,4})\s+(.*)", line)
        if m:
            yield "h", (len(m.group(1)), m.group(2))
        elif re.match(r"^\s*[-*•]\s+", line):
            yield "li", re.sub(r"^\s*[-*•]\s+", "", line)
        elif re.match(r"^\s*\d+[.)]\s+", line):
            yield "ol", re.sub(r"^\s*\d+[.)]\s+", "", line)
        elif re.fullmatch(r"\s*(-{3,}|\*{3,})\s*", line):
            pass  # horizontal rule
        else:
            yield "p", line.strip()
        i += 1


def inline_runs(text: str) -> list[tuple[str, bool, bool]]:
    """Split **bold** / *italic* / `code` / [link](url) into (text, bold, italic) runs."""
    text = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r"\1 (\2)", text).replace("`", "")
    runs = []
    # Underscore italics only at word boundaries, so snake_case names like get_macro_indicator stay intact.
    for tok in re.split(r"(\*\*[^*]+\*\*|(?<![\w*])\*[^*\s][^*]*\*(?![\w*])|(?<!\w)_[^_\s][^_]*_(?!\w))", text):
        if not tok:
            continue
        if tok.startswith("**") and tok.endswith("**"):
            runs.append((tok[2:-2], True, False))
        elif (tok.startswith("*") and tok.endswith("*")) or (tok.startswith("_") and tok.endswith("_") and len(tok) > 2):
            runs.append((tok[1:-1], False, True))
        else:
            runs.append((tok, False, False))
    return runs


def plain(text: str) -> str:
    return "".join(r[0] for r in inline_runs(text))


# ---------------------------------------------------------------- Word

def to_docx(report: dict) -> bytes:
    from docx import Document
    from docx.shared import Pt

    doc = Document()
    doc.styles["Normal"].font.size = Pt(10.5)

    def para(text, style=None):
        p = doc.add_paragraph(style=style)
        for t, b, it in inline_runs(text):
            run = p.add_run(t)
            run.bold, run.italic = b, it
        return p

    for kind, val in blocks(to_markdown(report)):
        if kind == "h":
            doc.add_heading(plain(val[1]), level=min(val[0] - 1, 3) if val[0] > 1 else 0)
        elif kind == "li":
            para(val, "List Bullet")
        elif kind == "ol":
            para(val, "List Number")
        elif kind == "table" and val:
            width = max(len(r) for r in val)
            t = doc.add_table(rows=0, cols=width)
            t.style = "Light Grid Accent 1"
            for ri, row in enumerate(val):
                cells = t.add_row().cells
                for ci in range(width):
                    cells[ci].text = plain(row[ci]) if ci < len(row) else ""
                    if ri == 0:
                        for r in cells[ci].paragraphs[0].runs:
                            r.bold = True
        else:
            para(val)
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


# ---------------------------------------------------------------- PDF

def _font(pdf) -> str:
    for d in FONT_DIRS:
        reg, bold = d / "DejaVuSans.ttf", d / "DejaVuSans-Bold.ttf"
        if reg.exists():
            pdf.add_font("DejaVu", "", str(reg))
            pdf.add_font("DejaVu", "B", str(bold if bold.exists() else reg))
            pdf.add_font("DejaVu", "I", str(reg))
            return "DejaVu"
    return "Helvetica"  # core font: Latin-1 only, text is sanitised below


def to_pdf(report: dict) -> bytes:
    from fpdf import FPDF

    pdf = FPDF(format="A4")
    pdf.set_auto_page_break(True, margin=15)
    pdf.add_page()
    family = _font(pdf)

    def clean(t: str) -> str:
        if family == "DejaVu":
            return t
        t = t.replace("€", "EUR ").replace("–", "-").replace("—", "-").replace("’", "'").replace("“", '"').replace("”", '"')
        return t.encode("latin-1", "replace").decode("latin-1")

    def write(text, size=10, style="", indent=0):
        pdf.set_font(family, style, size)
        pdf.set_x(pdf.l_margin + indent)
        # fpdf2's markdown: **bold**, __italic__. Rebuild from our runs so single _x_ / *x* italics render properly.
        md = "".join(f"**{t}**" if b else f"__{t}__" if it else t for t, b, it in inline_runs(clean(text).replace("__", "")))
        pdf.multi_cell(pdf.epw - indent, size * 0.5, md, markdown=True, new_x="LMARGIN", new_y="NEXT")

    for kind, val in blocks(to_markdown(report)):
        if kind == "h":
            size = {1: 16, 2: 13, 3: 11.5}.get(val[0], 11)
            pdf.ln(2)
            write(plain(val[1]), size, "B")
            pdf.ln(1)
        elif kind == "li":
            write("• " + val if family == "DejaVu" else "- " + val, indent=4)
        elif kind == "ol":
            write(val, indent=4)
        elif kind == "table" and val:
            width = max(len(r) for r in val)
            pdf.set_font(family, "", 7.5)
            with pdf.table(text_align="LEFT", line_height=3.6, first_row_as_headings=True) as t:
                for row in val:
                    r = t.row()
                    for ci in range(width):
                        r.cell(clean(plain(row[ci])) if ci < len(row) else "")
            pdf.ln(2)
        else:
            write(val)
            pdf.ln(1)
    return bytes(pdf.output())
